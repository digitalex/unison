func eventTypes(evs []Event) []string {
	out := []string{}
	for _, e := range evs {
		out = append(out, e.Type)
	}
	return out
}

func sameTypes(got []Event, want ...string) bool {
	types := eventTypes(got)
	if len(types) != len(want) {
		return false
	}
	for i := range want {
		if types[i] != want[i] {
			return false
		}
	}
	return true
}

func TestJoinAsUserIsIdempotent(t *testing.T) {
	s, now := newStore(t)
	ctx := context.Background()
	ws, _, _ := s.CreateWorkspace(ctx, "W", "", "")
	u, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "1", Name: "Alex"})

	p, token, existing, evs, err := s.JoinAsUser(ctx, ws.ID, u.ID, "Alex", "🧑")
	if err != nil || existing || p.UserID != u.ID || token == "" {
		t.Fatalf("first JoinAsUser = %+v %q %v %v", p, token, existing, err)
	}
	if !sameTypes(evs, "participant.joined", "member.added") {
		t.Errorf("events = %v", eventTypes(evs))
	}
	if auth, _ := s.Authenticate(ctx, token); auth.UserID != u.ID {
		t.Errorf("Authenticate = %+v, want linked", auth)
	}

	// Joining again (another device, another name) returns the same
	// participant and token: no duplicate, no events.
	*now = now.Add(time.Second)
	again, token2, existing, evs, err := s.JoinAsUser(ctx, ws.ID, u.ID, "AlexPhone", "")
	if err != nil || !existing || again.ID != p.ID || token2 != token || len(evs) != 0 {
		t.Fatalf("second JoinAsUser = %+v %q %v %v %v", again, token2, existing, eventTypes(evs), err)
	}
	m, _ := s.ListMembers(ctx, ws.ID)
	if len(m.Members) != 1 || len(m.Members[0].Participants) != 1 {
		t.Errorf("members = %+v", m)
	}
	if _, _, _, _, err := s.JoinAsUser(ctx, "ws_missing", u.ID, "", ""); !errors.Is(err, ErrNotFound) {
		t.Errorf("unknown workspace err = %v", err)
	}
	// Plain joins (agents) are unchanged: unlinked, no membership.
	agent, _, evs, _ := s.Join(ctx, ws.ID, "Quill", "🦉")
	if agent.UserID != 0 || !sameTypes(evs, "participant.joined") {
		t.Errorf("agent join = %+v %v", agent, eventTypes(evs))
	}
}

func TestRemoveMember(t *testing.T) {
	s, _ := newStore(t)
	ctx := context.Background()
	ws, _, _ := s.CreateWorkspace(ctx, "W", "", "")
	alex, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "1", Name: "Alex"})
	bob, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "2", Name: "Bob"})
	carol, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "3", Name: "Carol"})
	ap, _, _, _, _ := s.JoinAsUser(ctx, ws.ID, alex.ID, "Alex", "")
	bp, _, _, _, _ := s.JoinAsUser(ctx, ws.ID, bob.ID, "Bob", "")

	if _, err := s.RemoveMember(ctx, ws.ID, carol.ID, bob.ID); !errors.Is(err, ErrForbidden) {
		t.Errorf("non-member removing err = %v", err)
	}
	evs, err := s.RemoveMember(ctx, ws.ID, alex.ID, bob.ID)
	if err != nil || !sameTypes(evs, "member.removed") || evs[0].ActorID != ap.ID {
		t.Fatalf("remove = %v %v", evs, err)
	}
	if _, err := s.RemoveMember(ctx, ws.ID, alex.ID, bob.ID); !errors.Is(err, ErrNotFound) {
		t.Errorf("removing twice err = %v", err)
	}
	if ok, _ := s.IsMember(ctx, ws.ID, bob.ID); ok {
		t.Error("Bob is still a member")
	}
	// Bob's participant stays (history), still linked to his account, but
	// he is no longer listed.
	m, _ := s.ListMembers(ctx, ws.ID)
	if len(m.Members) != 1 || m.Members[0].UserID == bob.ID {
		t.Errorf("members after removal = %+v", m)
	}
	if p, _ := s.GetParticipant(ctx, ws.ID, bp.ID); p == nil || p.UserID != bob.ID {
		t.Errorf("Bob's participant after removal = %+v", p)
	}
	// Any member may remove any member, themselves included.
	if _, err := s.RemoveMember(ctx, ws.ID, alex.ID, alex.ID); err != nil {
		t.Errorf("leaving err = %v", err)
	}
}

// TestParticipantUserIDMigration opens a database created before membership
// (participants without user_id, no users table), as on production, and
// checks the column is added once, existing participants stay unlinked and
// working, and later boots are no-ops.
func TestParticipantUserIDMigration(t *testing.T) {
	dsn := storetest.DSN(t)
	ctx := context.Background()
	raw, err := openRaw(dsn)
	if err != nil {
		t.Fatal(err)
	}
	ddl := []string{
		`CREATE TABLE workspaces (id TEXT PRIMARY KEY, name TEXT NOT NULL, repo_url TEXT NOT NULL DEFAULT '', canvas_url TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL)`,
		`CREATE TABLE participants (id ` + map[bool]string{true: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", false: "INTEGER PRIMARY KEY AUTOINCREMENT"}[raw.pg] +
			`, workspace_id TEXT NOT NULL REFERENCES workspaces(id), name TEXT NOT NULL, emoji TEXT NOT NULL, status TEXT NOT NULL DEFAULT '', token TEXT NOT NULL UNIQUE, created_at BIGINT NOT NULL, last_seen_at BIGINT NOT NULL)`,
		`INSERT INTO workspaces (id, name, created_at) VALUES ('ws_legacy', 'Legacy', 1)`,
		`INSERT INTO participants (workspace_id, name, emoji, token, created_at, last_seen_at) VALUES ('ws_legacy', 'Alex', '🧑', 'legacytoken', 1, 1)`,
	}
	for _, q := range ddl {
		if _, err := raw.Exec(q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	raw.Close()

	for boot := 1; boot <= 3; boot++ {
		s, err := Open(dsn)
		if err != nil {
			t.Fatalf("boot %d: %v", boot, err)
		}
		p, err := s.Authenticate(ctx, "legacytoken")
		if err != nil || p.Name != "Alex" || p.UserID != 0 {
			t.Fatalf("boot %d: legacy participant = %+v %v", boot, p, err)
		}
		if boot == 2 {
			u, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "1", Name: "Alex"})
			if _, _, _, _, err := s.JoinAsUser(ctx, "ws_legacy", u.ID, "AlexNew", ""); err != nil {
				t.Fatalf("joining as a user after migration: %v", err)
			}
		}
		if boot == 3 {
			if m, _ := s.ListMembers(ctx, "ws_legacy"); len(m.Members) != 1 || m.Members[0].Participants[0].Name != "AlexNew" {
				t.Errorf("boot 3: members = %+v (the membership must survive reboots; the legacy row stays)", m)
			}
		}
		s.Close()
	}
}

// openRaw connects without applying the schema (to build legacy databases).
func openRaw(dsn string) (db, error) {
	if IsPostgresDSN(dsn) {
		conn, err := sql.Open("pgx", dsn)
		return db{DB: conn, pg: true}, err
	}
	conn, err := sql.Open("sqlite", dsn)
	return db{DB: conn}, err
}

// TestMemberParticipant: one call answers membership and finds the
// participant: a member who joined, a member who hasn't, and someone whose
// membership was removed (their participant stays, for history).
func TestMemberParticipant(t *testing.T) {
	s, _ := newStore(t)
	ctx := context.Background()
	alex, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "1", Name: "Alex"})
	bob, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "2", Name: "Bob"})
	cy, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "3", Name: "Cy"})
	ws, _, _ := s.CreateWorkspaceFor(ctx, alex.ID, "W", "", "")
	a, _, _, _, _ := s.JoinAsUser(ctx, ws.ID, alex.ID, "Alex", "")
	b, _, _, _, _ := s.JoinAsUser(ctx, ws.ID, bob.ID, "Bob", "")
	if _, err := s.RemoveMember(ctx, ws.ID, alex.ID, bob.ID); err != nil {
		t.Fatal(err)
	}
	if member, p, err := s.MemberParticipant(ctx, ws.ID, alex.ID); err != nil || !member || p == nil || p.ID != a.ID {
		t.Errorf("Alex: %v %+v %v, want member with participant %d", member, p, err, a.ID)
	}
	if member, p, err := s.MemberParticipant(ctx, ws.ID, bob.ID); err != nil || member || p != nil {
		t.Errorf("Bob (removed; participant %d stays): %v %+v %v, want not a member", b.ID, member, p, err)
	}
	if member, p, err := s.MemberParticipant(ctx, ws.ID, cy.ID); err != nil || member || p != nil {
		t.Errorf("Cy (never a member): %v %+v %v", member, p, err)
	}
	// A member who hasn't joined yet: a member, no participant.
	if _, err := s.db.ExecContext(ctx, rebind(s.db.pg, `INSERT INTO memberships (workspace_id, user_id, created_at) VALUES (?, ?, 1)`), ws.ID, cy.ID); err != nil {
		t.Fatal(err)
	}
	if member, p, err := s.MemberParticipant(ctx, ws.ID, cy.ID); err != nil || !member || p != nil {
		t.Errorf("Cy (member, not joined): %v %+v %v, want member without participant", member, p, err)
	}
}

// TestMergeAccountParticipants: a database from before #99 has an account
// with three participants in a workspace (one per device). Boot merges them
// into the oldest: their messages, items, comments, reactions, actions and
// event actors move to it, duplicates collapse, and later boots are no-ops.
// After that a second participant for the account is refused.
func TestMergeAccountParticipants(t *testing.T) {
	dsn := storetest.DSN(t)
	ctx := context.Background()
	s, err := Open(dsn)
	if err != nil {
		t.Fatal(err)
	}
	ws, _, _ := s.CreateWorkspace(ctx, "W", "", "")
	u, _ := s.LoginWithProvider(ctx, "github", Profile{Subject: "1", Name: "Alex"})
	keep, _, _, _, err := s.JoinAsUser(ctx, ws.ID, u.ID, "Alex", "🦊")
	if err != nil {
		t.Fatal(err)
	}
	phone, _, _, _ := s.Join(ctx, ws.ID, "AlexPhone", "")
	laptop, _, _, _ := s.Join(ctx, ws.ID, "AlexLaptop", "")
	ada, _, _, _ := s.Join(ctx, ws.ID, "Ada", "")

	m1, _, _ := s.PostMessage(ctx, keep, "from the desk", nil, nil)
	m2, _, _ := s.PostMessage(ctx, phone, "from the phone", nil, nil)
	m3, _, _ := s.PostMessage(ctx, ada, "please look", nil, nil)
	it, _, err := s.AddItem(ctx, phone, "Ship it", "", 0)
	if err != nil {
		t.Fatal(err)
	}
	c, _, err := s.AddComment(ctx, laptop, it.ID, "on it")
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range []struct {
		p     *Participant
		emoji string
	}{{keep, "👍"}, {phone, "👍"}, {phone, "❤️"}} {
		if _, _, err := s.React(ctx, r.p, m1.ID, r.emoji, true); err != nil {
			t.Fatal(err)
		}
	}
	s.Close()

	// Make it the legacy shape: phone and laptop linked to the same account
	// (laptop seen last), and actions asking both the desk and the phone.
	raw, err := openRaw(dsn)
	if err != nil {
		t.Fatal(err)
	}
	for _, q := range []struct {
		q    string
		args []any
	}{
		{`DROP INDEX IF EXISTS participants_user_once`, nil},
		{`UPDATE participants SET user_id = ? WHERE id IN (?, ?)`, []any{u.ID, phone.ID, laptop.ID}},
		{`UPDATE participants SET last_seen_at = 99999999999999 WHERE id = ?`, []any{laptop.ID}},
		{`UPDATE items SET assignee_id = ? WHERE id = ?`, []any{laptop.ID, it.ID}},
		{`INSERT INTO message_actions (workspace_id, message_id, participant_id, done_at) VALUES (?, ?, ?, NULL)`, []any{ws.ID, m3.ID, keep.ID}},
		{`INSERT INTO message_actions (workspace_id, message_id, participant_id, done_at) VALUES (?, ?, ?, 5)`, []any{ws.ID, m3.ID, phone.ID}},
		{`INSERT INTO message_actions (workspace_id, message_id, participant_id, done_at) VALUES (?, ?, ?, NULL)`, []any{ws.ID, m2.ID, laptop.ID}},
	} {
		if _, err := raw.Exec(rebind(raw.pg, q.q), q.args...); err != nil {
			t.Fatalf("%s: %v", q.q, err)
		}
	}
	raw.Close()

	count := func(s *Store, q string, args ...any) int {
		t.Helper()
		var n int
		if err := s.db.QueryRow(rebind(s.db.pg, q), args...).Scan(&n); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
		return n
	}
	for boot := 1; boot <= 2; boot++ {
		s, err := Open(dsn)
		if err != nil {
			t.Fatalf("boot %d: %v", boot, err)
		}
		p, err := s.UserParticipant(ctx, ws.ID, u.ID)
		if err != nil || p.ID != keep.ID || p.LastSeenAt != 99999999999999 {
			t.Errorf("boot %d: UserParticipant = %+v, %v; want #%d with the laptop's last-seen time", boot, p, err, keep.ID)
		}
		if n := count(s, `SELECT COUNT(*) FROM participants WHERE workspace_id = ?`, ws.ID); n != 2 {
			t.Errorf("boot %d: %d participants, want 2 (Alex and Ada)", boot, n)
		}
		msgs, _ := s.ListMessages(ctx, ws.ID, 0)
		for _, m := range msgs {
			if m.ID == m2.ID && m.AuthorID != keep.ID {
				t.Errorf("boot %d: the phone's message is by %d, want %d", boot, m.AuthorID, keep.ID)
			}
			if m.ID == m1.ID && (len(m.Reactions) != 2 || m.Reactions[0].Count != 1) {
				t.Errorf("boot %d: reactions = %+v, want one 👍 and one ❤️, both by Alex", boot, m.Reactions)
			}
			if m.ID == m3.ID && (len(m.ActionFor) != 1 || m.ActionFor[0] != keep.ID || len(m.DoneBy) != 1) {
				t.Errorf("boot %d: action for %v done by %v; want Alex, done (the phone had marked it)", boot, m.ActionFor, m.DoneBy)
			}
			if m.ID == m2.ID && (len(m.ActionFor) != 1 || m.ActionFor[0] != keep.ID) {
				t.Errorf("boot %d: action on m2 for %v, want Alex", boot, m.ActionFor)
			}
		}
		got, _, _ := s.GetItem(ctx, ws.ID, it.ID)
		if got.AssigneeID == nil || *got.AssigneeID != keep.ID || count(s, `SELECT COUNT(*) FROM items WHERE id = ? AND created_by = ?`, it.ID, keep.ID) != 1 {
			t.Errorf("boot %d: item = %+v, want created by and assigned to Alex", boot, got)
		}
		if count(s, `SELECT COUNT(*) FROM item_comments WHERE id = ? AND author_id = ?`, c.ID, keep.ID) != 1 {
			t.Errorf("boot %d: the comment didn't move to Alex", boot)
		}
		if n := count(s, `SELECT COUNT(*) FROM events WHERE actor_id IN (?, ?)`, phone.ID, laptop.ID); n != 0 {
			t.Errorf("boot %d: %d events still name the merged participants", boot, n)
		}
		s.Close()
	}

	// One participant per account from now on.
	raw, _ = openRaw(dsn)
	defer raw.Close()
	if _, err := raw.Exec(rebind(raw.pg, `UPDATE participants SET user_id = ? WHERE id = ?`), u.ID, ada.ID); err == nil {
		t.Error("a second participant for the account was allowed")
	}
}
