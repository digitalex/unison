// tableExists reports whether the named table exists in the store's schema.
func tableExists(t *testing.T, s *Store, name string) bool {
	t.Helper()
	q := `SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?`
	if s.db.pg {
		q = `SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?`
	}
	var n int
	if err := s.db.QueryRow(rebind(s.db.pg, q), name).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n > 0
}

// TestDropRemovedMetricsTable: a database from before backlog #22 has a
// metrics table, with a row linked to its "Track metric" backlog item. Boot
// drops the table and keeps the item; later boots are no-ops.
func TestDropRemovedMetricsTable(t *testing.T) {
	dsn := storetest.DSN(t)
	ctx := context.Background()
	s, err := Open(dsn)
	if err != nil {
		t.Fatal(err)
	}
	ws, _, _ := s.CreateWorkspace(ctx, "W", "", "")
	p, _, _, _ := s.Join(ctx, ws.ID, "Ada", "")
	item, _, err := s.AddItem(ctx, p, "Track metric: Build time", "", 0)
	if err != nil {
		t.Fatal(err)
	}
	s.Close()

	// The metrics schema as it was, in this dialect.
	raw, err := openRaw(dsn)
	if err != nil {
		t.Fatal(err)
	}
	id, real := "INTEGER PRIMARY KEY AUTOINCREMENT", "REAL"
	if raw.pg {
		id, real = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "DOUBLE PRECISION"
	}
	for _, q := range []string{
		`CREATE TABLE metrics (id ` + id + `, workspace_id TEXT NOT NULL REFERENCES workspaces(id), name TEXT NOT NULL,
			description TEXT NOT NULL DEFAULT '', direction TEXT NOT NULL CHECK (direction IN ('increase', 'decrease')),
			unit TEXT NOT NULL DEFAULT '', target ` + real + `, item_id BIGINT REFERENCES items(id),
			created_by BIGINT NOT NULL REFERENCES participants(id), created_at BIGINT NOT NULL)`,
		`CREATE UNIQUE INDEX metrics_name ON metrics(workspace_id, name)`,
	} {
		if _, err := raw.Exec(q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	if _, err := raw.Exec(rebind(raw.pg, `INSERT INTO metrics (workspace_id, name, direction, target, item_id, created_by, created_at) VALUES (?, 'Build time', 'decrease', 30, ?, ?, 1)`),
		ws.ID, item.ID, p.ID); err != nil {
		t.Fatal(err)
	}
	raw.Close()

	for boot := 1; boot <= 2; boot++ {
		s, err := Open(dsn)
		if err != nil {
			t.Fatalf("boot %d: %v", boot, err)
		}
		if tableExists(t, s, "metrics") {
			t.Errorf("boot %d: the metrics table still exists", boot)
		}
		if got, _, err := s.GetItem(ctx, ws.ID, item.ID); err != nil || got.Title != "Track metric: Build time" {
			t.Errorf("boot %d: tracking item = %+v, %v (it must stay an ordinary item)", boot, got, err)
		}
		s.Close()
	}
}

func TestMigrateAssignedItemsToInProgress(t *testing.T) {
	dsn := storetest.DSN(t)
	ctx := context.Background()
	s, err := Open(dsn)
	if err != nil {
		t.Fatal(err)
	}
	ws, _, _ := s.CreateWorkspace(ctx, "W", "", "")
	p, _, _, _ := s.Join(ctx, ws.ID, "Ada", "")
	item, _, err := s.StartItem(ctx, p, mustAddItem(t, s, p, "Legacy assigned"))
	if err != nil {
		t.Fatal(err)
	}
	s.Close()

	raw, err := openRaw(dsn)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := raw.Exec(rebind(raw.pg, `UPDATE items SET status = 'assigned' WHERE id = ?`), item.ID); err != nil {
		t.Fatal(err)
	}
	raw.Close()

	for boot := 1; boot <= 2; boot++ {
		s, err := Open(dsn)
		if err != nil {
			t.Fatalf("boot %d: %v", boot, err)
		}
		got, _, err := s.GetItem(ctx, ws.ID, item.ID)
		if err != nil {
			t.Fatalf("boot %d GetItem: %v", boot, err)
		}
		if got.Status != StatusInProgress || got.AssigneeID == nil || *got.AssigneeID != p.ID || got.LeaseExpiresAt == nil {
			t.Errorf("boot %d: item = %+v, want status=in_progress with assignee and lease preserved", boot, got)
		}
		s.Close()
	}
}

func mustAddItem(t *testing.T, s *Store, p *Participant, title string) int64 {
	t.Helper()
	it, _, err := s.AddItem(context.Background(), p, title, "", 0)
	if err != nil {
		t.Fatal(err)
	}
	return it.ID
}
