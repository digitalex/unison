// TestMessageAboutItem: a message can be tied to an item of its workspace;
// the item counts and lists it; replies inherit nothing.
func TestMessageAboutItem(t *testing.T) {
	s, _, a, b := setup(t)
	ctx := context.Background()
	it, _, _ := s.AddItem(ctx, a, "Landing page", "", 0)
	m, evs, err := s.PostMessage(ctx, a, "Starting on the hero", nil, &it.ID)
	if err != nil {
		t.Fatal(err)
	}
	if m.ItemID == nil || *m.ItemID != it.ID || m.Item == nil || m.Item.Title != "Landing page" || m.Item.Status != StatusOpen {
		t.Errorf("message = %+v", m)
	}
	var data Message
	if len(evs) != 1 || evs[0].Type != "message.created" || json.Unmarshal(evs[0].Data, &data) != nil || data.ItemID == nil || *data.ItemID != it.ID {
		t.Errorf("event = %+v", evs)
	}
	reply, _, _ := s.PostMessage(ctx, b, "nice", &m.ID, nil)
	if reply.ItemID != nil {
		t.Errorf("reply inherited item %d", *reply.ItemID)
	}
	s.PostMessage(ctx, b, "unrelated", nil, nil)

	got, _, _ := s.GetItem(ctx, a.WorkspaceID, it.ID)
	if got.MessageCount != 1 {
		t.Errorf("message_count = %d, want 1", got.MessageCount)
	}
	list, _, _ := s.ListBacklog(ctx, a.WorkspaceID, "")
	if list[0].MessageCount != 1 {
		t.Errorf("listed message_count = %d", list[0].MessageCount)
	}
	msgs, err := s.ItemMessages(ctx, a.WorkspaceID, it.ID)
	if err != nil || len(msgs) != 1 || msgs[0].ID != m.ID || msgs[0].Item.Title != "Landing page" {
		t.Errorf("ItemMessages = %+v %v", msgs, err)
	}
	all, _ := s.ListMessages(ctx, a.WorkspaceID, 0)
	if len(all) != 3 || all[0].Item == nil || all[1].Item != nil || all[2].ItemID != nil {
		t.Errorf("ListMessages = %+v", all)
	}
	if _, err := s.ItemMessages(ctx, a.WorkspaceID, 999); !errors.Is(err, ErrNotFound) {
		t.Errorf("messages of a missing item: %v", err)
	}
}

// TestMessageItemOtherWorkspace: an item id from another workspace (or none
// at all) is invalid, and nothing is posted.
func TestMessageItemOtherWorkspace(t *testing.T) {
	s, _, a, _ := setup(t)
	ctx := context.Background()
	ws2, _, _ := s.CreateWorkspace(ctx, "Other", "", "")
	c, _, _, _ := s.Join(ctx, ws2.ID, "Carol", "")
	theirs, _, _ := s.AddItem(ctx, c, "Their item", "", 0)
	for _, id := range []int64{theirs.ID, 999} {
		if _, _, err := s.PostMessage(ctx, a, "hi", nil, &id); !errors.Is(err, ErrInvalid) {
			t.Errorf("item %d: err = %v, want ErrInvalid", id, err)
		}
	}
	if msgs, _ := s.ListMessages(ctx, a.WorkspaceID, 0); len(msgs) != 0 {
		t.Errorf("posted anyway: %+v", msgs)
	}
}

// TestDeleteItemUnlinksMessages: deleting an item keeps its messages,
// untied, and says so with message.updated events.
func TestDeleteItemUnlinksMessages(t *testing.T) {
	s, _, a, _ := setup(t)
	ctx := context.Background()
	it, _, _ := s.AddItem(ctx, a, "Doomed", "", 0)
	m1, _, _ := s.PostMessage(ctx, a, "one", nil, &it.ID)
	m2, _, _ := s.PostMessage(ctx, a, "two", nil, &it.ID)
	evs, err := s.DeleteItem(ctx, a, it.ID)
	if err != nil {
		t.Fatal(err)
	}
	var types []string
	for _, e := range evs {
		types = append(types, e.Type)
	}
	if len(evs) != 3 || types[0] != "message.updated" || types[1] != "message.updated" || types[2] != "backlog.deleted" {
		t.Errorf("events = %v", types)
	}
	msgs, _ := s.ListMessages(ctx, a.WorkspaceID, 0)
	if len(msgs) != 2 || msgs[0].ID != m1.ID || msgs[1].ID != m2.ID || msgs[0].ItemID != nil || msgs[1].Item != nil {
		t.Errorf("messages after delete = %+v", msgs)
	}
}

// TestMessageItemMigration opens a database whose messages table predates
// item_id (as on production) and checks the column and index are added,
// old messages keep working, and later boots are no-ops.
func TestMessageItemMigration(t *testing.T) {
	dsn := storetest.DSN(t)
	ctx := context.Background()
	raw, err := openRaw(dsn)
	if err != nil {
		t.Fatal(err)
	}
	id := map[bool]string{true: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", false: "INTEGER PRIMARY KEY AUTOINCREMENT"}[raw.pg]
	ddl := []string{
		`CREATE TABLE workspaces (id TEXT PRIMARY KEY, name TEXT NOT NULL, repo_url TEXT NOT NULL DEFAULT '', canvas_url TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL)`,
		`CREATE TABLE participants (id ` + id + `, workspace_id TEXT NOT NULL REFERENCES workspaces(id), name TEXT NOT NULL, emoji TEXT NOT NULL, status TEXT NOT NULL DEFAULT '', token TEXT NOT NULL UNIQUE, created_at BIGINT NOT NULL, last_seen_at BIGINT NOT NULL)`,
		`CREATE TABLE messages (id ` + id + `, workspace_id TEXT NOT NULL REFERENCES workspaces(id), author_id BIGINT NOT NULL REFERENCES participants(id), parent_id BIGINT REFERENCES messages(id), body TEXT NOT NULL, created_at BIGINT NOT NULL)`,
		`INSERT INTO workspaces (id, name, created_at) VALUES ('ws_old', 'Old', 1)`,
		`INSERT INTO participants (workspace_id, name, emoji, token, created_at, last_seen_at) VALUES ('ws_old', 'Alex', '🧑', 'oldtoken', 1, 1)`,
		`INSERT INTO messages (workspace_id, author_id, body, created_at) VALUES ('ws_old', 1, 'from before', 1)`,
	}
	for _, q := range ddl {
		if _, err := raw.Exec(q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	raw.Close()

	for boot := 1; boot <= 3; boot++ {
		s, err := Open(dsn)
		if err != nil {
			t.Fatalf("boot %d: %v", boot, err)
		}
		msgs, err := s.ListMessages(ctx, "ws_old", 0)
		if err != nil || len(msgs) < 1 || msgs[0].Body != "from before" || msgs[0].ItemID != nil {
			t.Fatalf("boot %d: messages = %+v %v", boot, msgs, err)
		}
		if boot == 2 {
			p, _ := s.Authenticate(ctx, "oldtoken")
			it, _, _ := s.AddItem(ctx, p, "New item", "", 0)
			if _, _, err := s.PostMessage(ctx, p, "about it", nil, &it.ID); err != nil {
				t.Fatalf("posting about an item after migration: %v", err)
			}
		}
		if boot == 3 && (len(msgs) != 2 || msgs[1].Item == nil || msgs[1].Item.Title != "New item") {
			t.Errorf("boot 3: messages = %+v", msgs)
		}
		s.Close()
	}
}
